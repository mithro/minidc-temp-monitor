#!/usr/bin/env python3
"""Write common/ntc_table.h: thermistor temperature against divider ratio.

The divider is R1 from the supply to the ADC pin and the NTC from the pin to
ground, so the reading as a fraction of full scale is x = R / (R1 + R).  The
table holds the temperature in 0.01 C at x = i / 128; the firmware
interpolates between entries.
"""
import math
import sys

R1 = 100e3       # divider resistor, ohms
R0 = 100e3       # NTC resistance at T0
T0 = 25.0
BETA = 3950.0    # Sunlord SDNT1005X104F3950FTF
SHIFT = 9                       # 16-bit reading >> SHIFT = table index
STEPS = 65536 >> SHIFT          # 128


def temp_c(x):
    r = R1 * x / (1.0 - x)
    return 1.0 / (1.0 / (T0 + 273.15) + math.log(r / R0) / BETA) - 273.15


def table():
    # Entries 0 and STEPS are never used: the firmware rejects readings there.
    vals = [round(temp_c(i / STEPS) * 100) for i in range(1, STEPS)]
    return [vals[0]] + vals + [vals[-1]]


def render():
    t = table()
    out = ['/* Generated by tools/gen_ntc_table.py, do not edit.',
           f' * 100k NTC, B = {BETA:.0f}, with a {R1 / 1e3:.0f}k resistor to the supply.',
           f' * Temperature in 0.01 C at a reading of i/{STEPS} of full scale. */',
           f'#define NTC_SHIFT {SHIFT}',
           f'#define NTC_STEPS {STEPS}',
           'static const int16_t ntc_table[NTC_STEPS + 1] = {']
    out += ['\t' + ' '.join(f'{v},' for v in t[i:i + 8]) for i in range(0, len(t), 8)]
    return '\n'.join(out + ['};']) + '\n'


def main(argv):
    check = '--check' in argv
    paths = [a for a in argv if a != '--check']
    path = paths[0] if paths else 'common/ntc_table.h'
    if check:
        with open(path) as f:
            if f.read() != render():
                sys.exit(f'{path} is out of date: run tools/gen_ntc_table.py')
        return
    with open(path, 'w') as f:
        f.write(render())


if __name__ == '__main__':
    main(sys.argv[1:])
