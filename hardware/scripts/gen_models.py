#!/usr/bin/env python3
"""Write the simple 3D models KiCad's library does not ship.

  gen_models.py OUTDIR

The KiCad library has no model for the JST SH side-entry header or for the
2 x 2 mm UQFN-12, so the renders would show bare pads.  These are plain block
models, good enough to show size and keep-out, not for mechanical CAD.
Coordinates below are footprint millimetres (x right, y down, z up from the
board); VRML models in KiCad use 0.1 inch units with y up.
"""
import os
import sys

CREAM = (0.84, 0.81, 0.70)
DARK = (0.12, 0.12, 0.12)
BODY = (0.16, 0.16, 0.17)
TIN = (0.80, 0.80, 0.78)
MARK = (0.75, 0.75, 0.75)


def box(x0, x1, y0, y1, z0, z1, colour):
    u = 1 / 2.54
    cx, cy, cz = (x0 + x1) / 2 * u, -(y0 + y1) / 2 * u, (z0 + z1) / 2 * u
    sx, sy, sz = (x1 - x0) * u, (y1 - y0) * u, (z1 - z0) * u
    return ('Transform { translation %.4f %.4f %.4f children [ Shape {\n'
            '  appearance Appearance { material Material { diffuseColor %.2f %.2f %.2f '
            'specularColor 0.2 0.2 0.2 shininess 0.3 } }\n'
            '  geometry Box { size %.4f %.4f %.4f } } ] }\n'
            % (cx, cy, cz, *colour, sx, sy, sz))


def jst_sh_4_horizontal():
    """SM04B-SRSS-TB: housing 6.0 x 4.25 x 2.95 mm, cable entry on the +y face."""
    s = box(-3.0, 3.0, -1.675, 2.575, 0.0, 2.95, CREAM)
    s += box(-2.3, 2.3, 0.6, 2.59, 0.55, 2.45, DARK)          # cable entry
    for x in (-1.5, -0.5, 0.5, 1.5):
        s += box(x - 0.1, x + 0.1, -2.775, -1.675, 0.0, 0.2, TIN)   # signal tails
        s += box(x - 0.1, x + 0.1, 0.6, 2.2, 1.3, 1.5, TIN)         # contacts
    for sign in (-1, 1):                                       # solder tabs
        x0, x1 = sorted((sign * 3.0, sign * 3.4))
        s += box(x0, x1, 0.975, 2.775, 0.0, 0.9, TIN)
    return s


def uqfn12_2x2():
    """UQFN-12, 2.0 x 2.0 x 0.55 mm, pin 1 at top left."""
    return (box(-1.0, 1.0, -1.0, 1.0, 0.02, 0.55, BODY)
            + box(-0.8, -0.55, -0.8, -0.55, 0.55, 0.56, MARK))


MODELS = {
    'JST_SH_SM04B-SRSS-TB_1x04-1MP_P1.00mm_Horizontal.wrl': jst_sh_4_horizontal,
    'UQFN-12-1EP_2x2mm_P0.4mm_EP1.1x1.1mm.wrl': uqfn12_2x2,
}

if __name__ == '__main__':
    out = sys.argv[1]
    for name, fn in MODELS.items():
        with open(os.path.join(out, name), 'w') as f:
            f.write('#VRML V2.0 utf8\n# Generated by scripts/gen_models.py\n' + fn())
