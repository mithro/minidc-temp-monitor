#!/usr/bin/env python3
"""Price the boards from their JLC BOM files and write hardware/COST.md.

Part prices are a snapshot of the JLCPCB parts catalogue (price breaks per
LCSC number). Bare panel prices are JLCPCB's online quote for the uploaded
panel gerbers, and the assembly fees are JLCPCB's published Economic PCBA
fees. See QUOTES.md for how the figures were obtained.
Usage: cost.py   (rewrites COST.md for the quoted order of 15 panels)
"""
import csv
from pathlib import Path

SNAPSHOT = '18 Nov 2026'
HERE = Path(__file__).resolve().parent.parent

# LCSC number: (description, JLC library, [(minimum quantity, unit price USD), ...])
PRICES = {
    'C5346354': ('CH32V003J4M6', 'Extended', [(1, .268), (50, .2125), (150, .1886), (500, .1589), (2500, .1456), (4000, .1378)]),
    'C49006243': ('CH32V005D6U6', 'Extended', [(1, .2285), (50, .1799), (150, .1591), (500, .1329), (2500, .1214), (5000, .1144)]),
    'C7430446': ('JST SH 4-pin clone', 'Extended', [(1, .0675), (50, .0582), (150, .0533), (500, .0493), (2000, .0449), (4000, .0439)]),
    'C6807762': ('100k NTC, B3950, 1%', 'Extended', [(1, .0144), (200, .0117), (600, .0102), (2000, .0092), (10000, .0085)]),
    'C52923': ('1u 25 V X5R 0402', 'Basic', [(1, .0055), (1000, .0042), (3000, .0035)]),
    'C1525': ('100n 16 V X7R 0402', 'Basic', [(1, .0024), (1000, .0018), (3000, .0015)]),
    'C2286': ('Red LED 0603', 'Basic', [(1, .0077), (1000, .0059), (4000, .0046)]),
    'C25741': ('100k 1% 0402', 'Basic', [(1, .0009), (1000, .0007), (3000, .0006)]),
    'C11702': ('1k 1% 0402', 'Basic', [(1, .0013), (1000, .0011), (3000, .001)]),
    'C23162': ('4k7 1% 0603', 'Basic', [(1, .0028), (1000, .0022), (5000, .0019)]),
}

# The quoted order: 15 panels of 16 boards. Both JLCPCB and NextPCB price that
# quantity (NextPCB takes panels in multiples of 5), so the two can be compared.
PANELS, PER_PANEL = 15, 16

# Bare panels: JLCPCB online quote for out/panel/gerbers.zip on 18 Nov 2026,
# 15 panels, "Panel by Customer", 1.6 mm, green, 2 day build. The price was
# the same for both boards. See QUOTES.md.
PCB_QUOTE = {'HASL(with lead)': 24.40, 'LeadFree HASL': 26.50, 'ENIG': 45.90}
FINISH = {'sensor-ch32v003': 'LeadFree HASL', 'sensor-ch32v005': 'ENIG'}

# Assembly: JLCPCB's published Economic PCBA fees ("PCB Assembly Cost: What
# Does the Price Include?", updated 22 Oct 2026). Not a quote: JLCPCB only
# prices assembly after a sign-in.
SETUP = 8.18
STENCIL = 1.53
EXTENDED_FEE = 3.07      # per Extended part type
PER_JOINT = 0.0016       # SMT assembly, per solder joint
XRAY_EACH = [(1, 1.64), (11, .82), (51, .49), (201, .33), (501, .25), (1001, .16), (3001, .082)]
XRAY_PARTS = {'CH32V005D6U6'}    # leadless packages are X-rayed, charged per part
JOINTS = {'J': 6, 'U:CH32V003J4M6': 8, 'U:CH32V005D6U6': 13}  # anything else: 2


def unit_price(lcsc, qty):
    return [p for q, p in PRICES[lcsc][2] if qty >= q][-1]


def joints(refs, comment):
    key = refs[0].rstrip('0123456789')
    if key == 'U':                      # no default: an IC must be listed
        return len(refs) * JOINTS[f'U:{comment}']
    return len(refs) * JOINTS.get(key, 2)


def board(name, boards):
    with open(HERE / name / 'out' / 'bom-jlc.csv') as f:
        bom = [(r, r['Designator'].split(',')) for r in csv.DictReader(f)]
    per_board = {}                      # one part can span several BOM rows
    for r, refs in bom:
        per_board[r['LCSC']] = per_board.get(r['LCSC'], 0) + len(refs)
    ext = sum(PRICES[k][1] == 'Extended' for k in per_board)
    rows, parts, njoints = [], 0.0, 0
    for r, refs in bom:
        desc, lib, _ = PRICES[r['LCSC']]
        price = unit_price(r['LCSC'], per_board[r['LCSC']] * boards)
        parts += price * len(refs)
        njoints += joints(refs, r['Comment'])
        rows.append(f"| {r['Designator']} | {desc} | {r['LCSC']} | {lib} | {len(refs)} "
                    f"| {price:.4f} | {price * len(refs):.4f} |")
    finish = FINISH[name]
    fees = [('Parts', parts * boards),
            (f'Bare panels, {finish} (quoted)', PCB_QUOTE[finish]),
            ('Assembly setup and stencil', SETUP + STENCIL),
            (f'Extended part fee, {ext} types', ext * EXTENDED_FEE),
            (f'Placement, {njoints} joints per board', njoints * PER_JOINT * boards)]
    xray = sum(len(refs) for r, refs in bom if r['Comment'] in XRAY_PARTS) * boards
    if xray:
        each = [p for q, p in XRAY_EACH if xray >= q][-1]
        fees.append((f'X-ray inspection, {xray} QFN parts at {each}', xray * each))
    return rows, parts, fees


def main():
    boards = PANELS * PER_PANEL
    out = ['# Cost', '',
           f'Generated by `scripts/cost.py` for {boards} boards of each version ({PANELS} panels of',
           f'{PER_PANEL}) built by JLCPCB, relay fitting (R5 and R6 fitted, R3 and R4 not fitted),',
           'from `sensor-*/out/bom-jlc.csv`. All prices are in USD.', '',
           '- Bare panels: JLCPCB\'s online quote for the uploaded panel gerbers.',
           f'- Parts: JLCPCB catalogue prices on {SNAPSHOT} at the price break for the order',
           '  quantity.',
           '- Assembly: JLCPCB\'s published Economic PCBA fees. JLCPCB prices assembly',
           '  only after a sign-in, so these lines are calculated, not quoted.', '',
           'Shipping, tax, cables and spare parts for placement losses are not included.',
           '[QUOTES.md](QUOTES.md) has the quotes, how they were obtained and the',
           'comparison with NextPCB.', '']
    summary, detail = [], []
    for name in ('sensor-ch32v003', 'sensor-ch32v005'):
        rows, parts, fees = board(name, boards)
        total = sum(v for _, v in fees)
        summary.append(f'| `{name}` | {parts:.4f} | {parts * boards:.2f} | {total - parts * boards:.2f} '
                       f'| {total:.2f} | {total / boards:.2f} |')
        detail += [f'## {name}', '',
                '| Ref | Part | LCSC | JLC library | Qty | Unit price | Cost per board |',
                '|---|---|---|---|---|---|---|', *rows,
                f'| | **Parts per board** | | | | | **{parts:.4f}** |', '',
                f'| For {boards} boards | USD |', '|---|---|',
                *[f'| {k} | {v:.2f} |' for k, v in fees],
                f'| **Total** | **{total:.2f}** |', '']
    out += ['| Board | Parts per board | Parts | Panels and assembly | Total | Per board |',
            '|---|---|---|---|---|---|', *summary, '', *detail]
    (HERE / 'COST.md').write_text('\n'.join(out))
    print('\n'.join(out))


if __name__ == '__main__':
    main()
